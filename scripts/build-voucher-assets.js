// Regenerates netlify/functions/lib/voucher-assets.js — the voucher PDF's fonts
// and logo, embedded as base64 so the Netlify function that draws the PDF needs
// no file access at run time.
//
// Run from the repository root after changing anything in portal/fonts/Inter-*.ttf
// or portal/img/voucher-logo.png:
//     node scripts/build-voucher-assets.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const files = {
  regular:  'portal/fonts/Inter-Regular.ttf',
  italic:   'portal/fonts/Inter-Italic.ttf',
  semibold: 'portal/fonts/Inter-SemiBold.ttf',
  extra:    'portal/fonts/Inter-ExtraBold.ttf',
  logo:     'portal/img/voucher-logo.png',
};
let out = '// GENERATED by scripts/build-voucher-assets.js — do not edit by hand.\n' +
          '// The fonts and logo that portal/js/voucher-pdf.js draws the voucher with.\n' +
          "'use strict';\nmodule.exports = {\n";
for (const [k, f] of Object.entries(files)) {
  out += `  ${k}: '${fs.readFileSync(path.join(root, f)).toString('base64')}',\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'netlify/functions/lib/voucher-assets.js'), out);
console.log('wrote netlify/functions/lib/voucher-assets.js (' + out.length + ' bytes)');
